/* ─────────────────────────────────────────────────────────────────────────
   scripts/build-cohorts.mjs

   Renders the next cohort into the hand-written pages.

   Each slot is wrapped in markers so re-running is idempotent and a slot can
   be moved without touching this script:

     <!-- cohort:hero -->…<!-- /cohort:hero -->

   Pages regenerated by other build steps (e.g. /enrol/) render their cohort
   line from scripts/cohorts.mjs directly, so nothing is wiped by a rebuild.

     node scripts/build-cohorts.mjs
   ───────────────────────────────────────────────────────────────────────── */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { resolveCohort, renderCohort } from './cohorts.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = path.join(ROOT, 'public');

const TARGETS = [
  { file: 'index.html', slots: ['hero', 'banner', 'pricing'] },
  { file: 'bootcamps/index.html', slots: ['hero'] },
  { file: 'become-a-member/index.html', slots: ['apply'] },
];

const res = resolveCohort();

let written = 0;
let missing = 0;

for (const target of TARGETS) {
  const file = path.join(PUBLIC, target.file);
  if (!fs.existsSync(file)) {
    console.log(`  ! missing page: ${target.file}`);
    continue;
  }

  let html = fs.readFileSync(file, 'utf8');
  const original = html;

  for (const slot of target.slots) {
    const re = new RegExp(`<!-- cohort:${slot} -->[\\s\\S]*?<!-- /cohort:${slot} -->`);
    if (!re.test(html)) {
      missing++;
      console.log(`  ! ${target.file}: no <!-- cohort:${slot} --> marker`);
      continue;
    }
    const html2 = renderCohort(slot, res);
    html = html.replace(re, `<!-- cohort:${slot} -->${html2}<!-- /cohort:${slot} -->`);
  }

  if (html !== original) {
    fs.writeFileSync(file, html, 'utf8');
    written++;
  }
}

const state = res.state;
const label = res.cohort
  ? `${res.cohort.label} · ${res.cohort.start} · applications close ${res.cohort.applyBy}`
  : 'no upcoming cohort';

console.log(`cohorts — ${state}: ${label} | pages written: ${written} | missing slots: ${missing}`);
if (state === 'none') {
  console.log('  ! every cohort in data/cohorts.json is in the past — add the next one');
}
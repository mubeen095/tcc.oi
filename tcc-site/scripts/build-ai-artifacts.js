/* ── helpers ───────────────────────────────────────────────────────────── */
function industries() {
  const list = Array.isArray(IND) ? IND : (IND.INDUSTRIES || IND.industries || []);
  return list.map(function (i) {
    return {
      id: i.id,
      name: i.name,
      roles: (i.roles || []).length
    };
  });
}


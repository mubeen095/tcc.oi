/* ── faq.jsonl ─────────────────────────────────────────────────────────── */
function buildFaqJsonl() {
  const rows = A.QA.map(function (item) {
    return JSON.stringify({
      q: item.q,
      a: item.a,
      group: item.group,
      url: item.url,
      site: SITE
    });
  });
  return rows.join('\n') + '\n';
}

/* ── write ─────────────────────────────────────────────────────────────── */
function write(name, content) {
  fs.writeFileSync(path.join(OUT, name), content, 'utf8');
  return name + ' (' + content.length.toLocaleString() + ' bytes)';
}


/* ─────────────────────────────────────────────────────────────────────────
   scripts/build-ai-artifacts.js

   Generates the AI-search (AEO/GEO) artifacts from data/ai-answers.js:

     public/ai.txt        → AI crawler policy + fact sheet
     public/llms.txt      → short index for LLMs
     public/llms-full.txt → full fact sheet + all Q&A
     public/llms.json     → structured entity + Q&A payload
     public/faq.jsonl     → one JSON question per line
     scripts/ai-entities.json         → consumed by HTML generators

   Run after editing data/ai-answers.js or data/industries.js:
     node scripts/build-ai-artifacts.js
   ───────────────────────────────────────────────────────────────────────── */

